"""Build the example content pack in content/example-town/.

Everything here is generated by this script: plain boxes, ramps and a
procedural checker texture. No third-party assets are used, so the result
is CC0 like the script output says.

Run from the project root:  python tools/make-example-pack.py
It is also a small, dependency-free example of writing a .glb from code.
"""
from __future__ import annotations

import argparse
import json
import math
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def png_rgba(width: int, height: int, pixel) -> bytes:
    rows = b"".join(
        b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(width)) for y in range(height)
    )

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 0)) + chunk(b"IEND", b"")


def ground_texture() -> bytes:
    """A soft paving pattern: 8x8 tiles with darker joints.

    Stored uncompressed (zlib level 0) so the file is byte-identical with
    every zlib build; the tests compare it with the committed copy.
    """

    def pixel(x: int, y: int):
        joint = x % 8 == 0 or y % 8 == 0
        tone = 120 if joint else 168 + ((x // 8 + y // 8) % 2) * 12
        return (tone, tone, tone - 8, 255)

    return png_rgba(64, 64, pixel)


def to_gltf(p):
    """Blender (east, north, up) to glTF (x, y up, -z north)."""
    return (p[0], p[2], -p[1])


class Mesh:
    def __init__(self, name: str, material: int, color=(1.0, 1.0, 1.0)):
        self.name, self.material, self.color = name, material, color
        self.positions: list[tuple] = []
        self.normals: list[tuple] = []
        self.uvs: list[tuple] = []
        self.indices: list[int] = []

    def quad(self, corners, normal, uv_scale=1.0):
        """Four Blender-space corners, counter-clockwise seen from `normal`."""
        base = len(self.positions)
        for c in corners:
            self.positions.append(to_gltf(c))
            self.normals.append(to_gltf(normal))
            # Planar UVs in metres so textures tile at a constant size.
            if abs(normal[2]) > 0.5:
                self.uvs.append((c[0] / uv_scale, c[1] / uv_scale))
            elif abs(normal[0]) > 0.5:
                self.uvs.append((c[1] / uv_scale, c[2] / uv_scale))
            else:
                self.uvs.append((c[0] / uv_scale, c[2] / uv_scale))
        self.indices += [base, base + 1, base + 2, base, base + 2, base + 3]

    def box(self, lo, hi):
        (x0, y0, z0), (x1, y1, z1) = lo, hi
        self.quad([(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)], (0, 0, 1))
        self.quad([(x0, y1, z0), (x1, y1, z0), (x1, y0, z0), (x0, y0, z0)], (0, 0, -1))
        self.quad([(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)], (1, 0, 0))
        self.quad([(x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1)], (-1, 0, 0))
        self.quad([(x1, y1, z0), (x0, y1, z0), (x0, y1, z1), (x1, y1, z1)], (0, 1, 0))
        self.quad([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)], (0, -1, 0))

    def ramp(self, x, y, z):
        """A slope rising northwards from y[0] (height z[0]) to y[1] (z[1])."""
        rise, run = z[1] - z[0], y[1] - y[0]
        n = (0.0, -rise / math.hypot(rise, run), run / math.hypot(rise, run))
        self.quad([(x[0], y[0], z[0]), (x[1], y[0], z[0]), (x[1], y[1], z[1]), (x[0], y[1], z[1])], n)


def build_meshes() -> list[Mesh]:
    meshes = []
    ground = Mesh("Ground", material=0)
    ground.quad([(-150, -150, 0), (150, -150, 0), (150, 150, 0), (-150, 150, 0)], (0, 0, 1), uv_scale=8.0)
    meshes.append(ground)

    road = Mesh("Road", material=1, color=(0.22, 0.22, 0.24))
    road.box((-6, -150, 0), (6, 150, 0.05))
    road.box((-150, -6, 0), (150, 6, 0.05))
    meshes.append(road)

    colours = [(0.85, 0.45, 0.3), (0.35, 0.55, 0.8), (0.9, 0.8, 0.45), (0.5, 0.75, 0.5)]
    buildings = Mesh("Buildings", material=1, color=(1, 1, 1))
    for i, (cx, cy) in enumerate([(30, 30), (-35, 32), (32, -40), (-30, -30), (70, 20), (-75, -15)]):
        height = 8 + (i * 7) % 20
        size = 10 + (i * 3) % 8
        sub = Mesh(f"Building{i}", material=1, color=colours[i % len(colours)])
        sub.box((cx - size, cy - size, 0), (cx + size, cy + size, height))
        meshes.append(sub)
    del buildings

    park = Mesh("JumpRamp", material=1, color=(0.95, 0.6, 0.2))
    park.ramp((-4, 4), (60, 80), (0, 4))
    park.box((-4, 80, 0), (4, 90, 4))
    meshes.append(park)

    stairs = Mesh("Stairs", material=1, color=(0.7, 0.7, 0.68))
    for step in range(16):
        stairs.box((-60 + step * 0.5, 60, 0), (-60 + step * 0.5 + 0.5, 70, 0.2 * (step + 1)))
    stairs.box((-52, 60, 0), (-44, 70, 3.2))
    meshes.append(stairs)

    # Decoration you can walk through: NOCOL_ means "drawn, not solid".
    flowers = Mesh("NOCOL_Flowers", material=1, color=(0.85, 0.3, 0.55))
    for k in range(10):
        a = k / 10 * math.tau
        x, y = 15 + 6 * math.cos(a), -15 + 6 * math.sin(a)
        flowers.box((x - 0.4, y - 0.4, 0), (x + 0.4, y + 0.4, 0.6))
    meshes.append(flowers)

    # Invisible walls at the edge: COL_ means "solid, never drawn".
    edge = Mesh("COL_EdgeWalls", material=1)
    for lo, hi in [((-151, -151, 0), (151, -150, 6)), ((-151, 150, 0), (151, 151, 6)),
                   ((-151, -150, 0), (-150, 150, 6)), ((150, -150, 0), (151, 150, 6))]:
        edge.box(lo, hi)
    meshes.append(edge)
    return meshes


def write_glb(meshes: list[Mesh], texture: bytes, path: Path):
    blob = bytearray()
    views, accessors, gltf_meshes, nodes = [], [], [], []

    def add_view(data: bytes, target=None) -> int:
        while len(blob) % 4:
            blob.append(0)
        view = {"buffer": 0, "byteOffset": len(blob), "byteLength": len(data)}
        if target:
            view["target"] = target
        blob.extend(data)
        views.append(view)
        return len(views) - 1

    def add_accessor(values, kind: str, component: int, fmt: str, minmax=False, target=34962) -> int:
        flat = [v for item in values for v in (item if isinstance(item, tuple) else (item,))]
        view = add_view(struct.pack(f"<{len(flat)}{fmt}", *flat), target)
        acc = {"bufferView": view, "componentType": component, "count": len(values), "type": kind}
        if minmax:
            acc["min"] = [min(v[i] for v in values) for i in range(3)]
            acc["max"] = [max(v[i] for v in values) for i in range(3)]
        accessors.append(acc)
        return len(accessors) - 1

    for mesh in meshes:
        attributes = {
            "POSITION": add_accessor(mesh.positions, "VEC3", 5126, "f", minmax=True),
            "NORMAL": add_accessor(mesh.normals, "VEC3", 5126, "f"),
            "TEXCOORD_0": add_accessor(mesh.uvs, "VEC2", 5126, "f"),
        }
        if mesh.material == 1:
            colour = tuple(mesh.color) + (1.0,)
            attributes["COLOR_0"] = add_accessor([colour] * len(mesh.positions), "VEC4", 5126, "f")
        indices = add_accessor(mesh.indices, "SCALAR", 5125, "I", target=34963)
        gltf_meshes.append({"name": mesh.name, "primitives": [
            {"attributes": attributes, "indices": indices, "material": mesh.material}]})
        nodes.append({"name": mesh.name, "mesh": len(gltf_meshes) - 1})

    image_view = add_view(texture)
    while len(blob) % 4:
        blob.append(0)
    document = {
        "asset": {"version": "2.0", "generator": "SARE tools/make-example-pack.py"},
        "scene": 0,
        "scenes": [{"nodes": list(range(len(nodes)))}],
        "nodes": nodes,
        "meshes": gltf_meshes,
        "materials": [
            {"name": "Paving", "pbrMetallicRoughness": {"baseColorTexture": {"index": 0}}},
            {"name": "Painted", "pbrMetallicRoughness": {"baseColorFactor": [1, 1, 1, 1]}},
        ],
        "textures": [{"source": 0, "sampler": 0}],
        "samplers": [{"wrapS": 10497, "wrapT": 10497}],
        "images": [{"bufferView": image_view, "mimeType": "image/png"}],
        "buffers": [{"byteLength": len(blob)}],
        "bufferViews": views,
        "accessors": accessors,
    }
    text = json.dumps(document, separators=(",", ":")).encode()
    text += b" " * (-len(text) % 4)
    out = struct.pack("<4sII", b"glTF", 2, 12 + 8 + len(text) + 8 + len(blob))
    out += struct.pack("<I4s", len(text), b"JSON") + text
    out += struct.pack("<I4s", len(blob), b"BIN\x00") + bytes(blob)
    path.write_bytes(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "content" / "example-town")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    write_glb(build_meshes(), ground_texture(), args.out / "world.glb")
    print(f"Wrote {args.out / 'world.glb'}")


if __name__ == "__main__":
    main()
